def day_key(now):
    return time.strftime("%Y-%m-%d", time.localtime(now))


def _absolute(value, field):
    if not isinstance(value, str) or not value:
        raise ValueError('INVALID_CONFIG: ' + field)
    path = Path(value).expanduser()
    if not path.is_absolute():
        raise ValueError('INVALID_CONFIG: %s must be absolute' % field)
    return str(path)


def _existing_doc(value, field):
    path = _absolute(value, field)
    if not Path(path).is_file():
        raise ValueError('%s_MISSING: %s' % (field.upper(), path))
    return path


def load_triggers(path):
    """Validate machine-local trigger config; fail closed on anything odd."""
    path = Path(path).expanduser().resolve()
    cfg = json.loads(path.read_text(encoding='utf-8'))
    if not isinstance(cfg, dict):
        raise ValueError('INVALID_CONFIG: root must be an object')
    unknown = set(cfg) - {'loop', 'repo_cwd', 'entry_doc', 'rules_doc', 'rules',
                          'cooldown_minutes', 'max_rounds_per_day', 'spawn'}
    if unknown:
        raise ValueError('INVALID_CONFIG: unknown keys ' + ','.join(sorted(unknown)))
    for key in ('loop', 'repo_cwd', 'entry_doc', 'rules_doc', 'rules'):
        if key not in cfg:
            raise ValueError('INVALID_CONFIG: missing ' + key)
    if cfg['loop'] not in LOOPS:
        raise ValueError('INVALID_CONFIG: loop must be one of ' + ','.join(LOOPS))
    cfg['repo_cwd'] = _absolute(cfg['repo_cwd'], 'repo_cwd')
    if not Path(cfg['repo_cwd']).is_dir():
        raise ValueError('REPO_CWD_MISSING: ' + cfg['repo_cwd'])
    cfg['entry_doc'] = _existing_doc(cfg['entry_doc'], 'entry_doc')
    cfg['rules_doc'] = _existing_doc(cfg['rules_doc'], 'rules_doc')
    rules = cfg['rules']
    if not isinstance(rules, list) or not rules:
        raise ValueError('INVALID_CONFIG: rules must be a non-empty list')
    for rule in rules:
        if not isinstance(rule, dict) or set(rule) != {'title_prefix_any'}:
            raise ValueError('INVALID_CONFIG: rule supports only title_prefix_any')
        prefixes = rule['title_prefix_any']
        if (not isinstance(prefixes, list) or not prefixes
                or not all(isinstance(x, str) and x for x in prefixes)):
            raise ValueError('INVALID_CONFIG: title_prefix_any')
    for key, default in (('cooldown_minutes', 30), ('max_rounds_per_day', 12)):
        value = cfg.get(key, default)
        if not isinstance(value, (int, float)) or isinstance(value, bool) or value <= 0:
            raise ValueError('INVALID_CONFIG: ' + key)
        cfg[key] = value
    spawn = cfg.get('spawn', {})
    if not isinstance(spawn, dict) or set(spawn) - {'command', 'prompt_template'}:
        raise ValueError('INVALID_CONFIG: spawn')
    command = spawn.get('command', DEFAULT_COMMAND)
    if (not isinstance(command, list) or not command
            or not all(isinstance(x, str) and x for x in command)):
        raise ValueError('INVALID_CONFIG: spawn.command')
    template = spawn.get('prompt_template', DEFAULT_PROMPT_TEMPLATE)
    if not isinstance(template, str):
        raise ValueError('INVALID_CONFIG: spawn.prompt_template')
    try:
        template.format(rules_doc='', entry_doc='')
    except (KeyError, IndexError, ValueError):
        raise ValueError('INVALID_CONFIG: prompt_template placeholders') from None
    if '{rules_doc}' not in template or '{entry_doc}' not in template:
        raise ValueError('INVALID_CONFIG: prompt_template needs both placeholders')
    cfg['spawn'] = {'command': command, 'prompt_template': template}
    return cfg


def load_state(state_dir):
    """Return (state, fresh); a missing or unreadable cursor means bootstrap."""
    path = Path(state_dir) / STATE_FILE
    if not path.is_file():
        return None, True
    try:
        state = json.loads(path.read_text(encoding='utf-8'))
    except ValueError:
        return None, True
    if not isinstance(state, dict) or not isinstance(state.get('seen'), dict):
        return None, True
    return state, False


def save_state(state_dir, state):
    directory = Path(state_dir)
    directory.mkdir(parents=True, exist_ok=True)
    tmp = directory / ('%s.tmp.%d' % (STATE_FILE, os.getpid()))
    tmp.write_text(json.dumps(state, ensure_ascii=False, indent=1), encoding='utf-8')
    os.replace(tmp, directory / STATE_FILE)


def log_decision(state_dir, ts, decision):
    if state_dir is None:
        return
    record = {k: v for k, v in decision.items() if k not in ('prompt', 'argv')}
    path = Path(state_dir) / LOG_FILE
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open('a', encoding='utf-8') as stream:
        stream.write(json.dumps(dict(ts=ts, **record), ensure_ascii=False) + '\n')


def issue_key(raw):
    for field in ('id', 'number'):
        key = raw.get(field)
        if not isinstance(key, bool) and isinstance(key, int) and key > 0:
            return key
    raise ValueError('MALFORMED_ISSUE_IDENTITY')


def match_rules(cfg, issues, seen):
    """First-seen only: an open issue whose title matches and is unseen.

    Seen keys are canonical strings — JSON round-trips turn int keys into
    strings and a mixed cursor would re-fire on every tick.
    """
    matched = []
    for raw in issues:
        if raw.get('state') != 'open':
            continue
        title = raw.get('title')
        if not isinstance(title, str):
            continue
        if not any(title.startswith(prefix)
                   for rule in cfg['rules'] for prefix in rule['title_prefix_any']):
            continue
        key = str(issue_key(raw))
        if key in seen:
            continue
        number = raw.get('number')
        matched.append((key, number if isinstance(number, int) and not isinstance(number, bool)
                        else int(key)))
    return matched


def _prompt_file(directory, key=None):
    """This round's own prompt copy. ``key`` (the execution id when the
    spawn adopts a prepared round) makes the file traceable; a missing
    or hostile key falls back to a random suffix — never a shared name."""
    safe = re.sub(r'[^A-Za-z0-9_-]', '', str(key or ''))[:64]
    return directory / ('%s%s.txt' % (PROMPT_FILE_PREFIX,
                        safe or uuid.uuid4().hex[:12]))


def _prune_prompt_files(directory, keep, now=None,
                        retention=PROMPT_RETENTION_SECONDS):
    """Drop prompt copies past retention (the file is a live stdin source,
    so only long-dead ones qualify), including the pre-rename shared
    name. Best effort: an undeletable file never fails a spawn."""
    now = time.time() if now is None else now
    for path in list(directory.glob(PROMPT_FILE_PREFIX + '*.txt')) + [
            directory / PROMPT_FILE_LEGACY]:
        if path == keep:
            continue
        try:
            if now - path.stat().st_mtime > retention:
                path.unlink()
        except OSError:
            pass

def spawn_log_path(state_dir, execution):
    """The per-round CLI log path (``<state_dir>/executions/<exec_id>.log``),
    or None when there is no valid execution id to key it by. One round, one
    file: the run-detail view streams it, and a process that dies before
    writing anything still leaves its own evidence. The id is validated to a
    32-hex execution id so a value that ever came from outside can never name
    a path."""
    exec_id = str(execution or '').lower()
    if not re.fullmatch(r'[0-9a-f]{32}', exec_id):
        return None
    return Path(state_dir) / 'executions' / (exec_id + '.log')


def spawn_worker(cfg, state_dir, prompt, dry_run, popen_fn=None, which_fn=None,
                 prompt_key=None, log_path=None):
    argv = resolve_command(cfg['spawn']['command'], which_fn)
    if dry_run:
        return {'pid': None, 'argv': argv, 'log': None, 'proc': None}
    directory = Path(state_dir)
    directory.mkdir(parents=True, exist_ok=True)
    prompt_file = _prompt_file(directory, prompt_key)
    prompt_file.write_text(prompt, encoding='utf-8')
    _prune_prompt_files(directory, keep=prompt_file)
    out_path = Path(log_path) if log_path else directory / SPAWN_LOG
    out_path.parent.mkdir(parents=True, exist_ok=True)
    kwargs = {}
    if os.name == 'nt':
        # CREATE_NO_WINDOW is documented as ignored beside DETACHED_PROCESS;
        # keep both so either semantics satisfies the no-console intent.
        kwargs['creationflags'] = subprocess.DETACHED_PROCESS | subprocess.CREATE_NO_WINDOW
    else:
        kwargs['start_new_session'] = True
    spawn = popen_fn or subprocess.Popen
    with prompt_file.open('rb') as stdin, out_path.open('ab') as out:
        proc = spawn(argv, cwd=cfg['repo_cwd'], stdin=stdin, stdout=out,
                     stderr=subprocess.STDOUT, **kwargs)
    # ``proc`` rides along so the caller can check the liveness of what it
    # just started: a process that dies in the first seconds must not sit on
    # the ledger as a live round.
    return {'pid': proc.pid, 'argv': argv, 'log': str(out_path), 'proc': proc}


def _decision(event, matched=None, reason=None, **extra):
    decision = {'ok': True, 'event': event,
                'matched_numbers': [n for _, n in (matched or [])],
                'reason': reason}
    decision.update(extra)
    return decision


def _advance_fire(state, now):
    today = day_key(now)
    state['fired_count'] = state['fired_count'] + 1 if state.get('fired_date') == today else 1
    state['fired_date'] = today
    state['last_fired'] = now


def _load_cp_config(path, cwd):
    from .cp.runtime import load_config
    return load_config(path, cwd=cwd)


def run(cfg_path, mode='run', dry_run=False, now=None, github_factory=None,
        service_factory=None, config_provider=None, popen_fn=None, which_fn=None,
        gitea_factory=None):
    """One deterministic trigger evaluation; never raises, returns a decision."""
    state_dir = None
    try:
        if mode not in ('check', 'run'):
            raise ValueError('UNKNOWN_MODE')
        now = time.time() if now is None else float(now)
        cfg = load_triggers(cfg_path)
        cp_path = Path(str(cfg_path)).expanduser().resolve().parent / 'control-plane.json'
        cp_cfg = (config_provider or _load_cp_config)(cp_path, cfg['repo_cwd'])
        state_dir = Path(cp_cfg['state_dir'])
        state, fresh = load_state(state_dir)
        if state is None:
            state = {'seen': {}, 'last_fired': 0.0,
                     'fired_date': day_key(now), 'fired_count': 0}

        def finish(decision):
            save_state(state_dir, state)
            log_decision(state_dir, now, decision)
            return decision

        if now - state['last_fired'] < cfg['cooldown_minutes'] * 60:
            return finish(_decision('SKIPPED_COOLDOWN', reason='cooldown window'))
        status = (service_factory or (lambda c: Service(c)))(cp_cfg).status()
        if not status.get('enabled'):
            return finish(_decision('SKIPPED_NOT_ENABLED', reason='machine not enabled'))
        platform_fn = github_factory or gitea_factory or (lambda p: GitHub(p))
        issues = platform_fn(cp_cfg['platform']).list_issues(state='open')
        state['seen'] = {k: v for k, v in state['seen'].items()
                         if k in {str(issue_key(raw)) for raw in issues}}
        matched = match_rules(cfg, issues, state['seen'])
        if fresh:
            # Bootstrap: prime the cursor without spawning so deploying the
            # trigger never mass-fires on pre-existing matching issues.
            state['seen'].update({k: {'number': n} for k, n in matched})
            return finish(_decision('SKIPPED_BOOTSTRAP', matched, 'cursor primed'))
        if not matched:
            return finish(_decision('SKIPPED_NO_MATCH', reason='no new matching issue'))
        if (status.get('executions') or {}).get('RUNNING', 0):
            # Busy is temporary: seen stays clean so a later tick can fire.
            return finish(_decision('SKIPPED_BUSY', matched, 'cp execution running'))
        if state['fired_date'] == day_key(now) and state['fired_count'] >= cfg['max_rounds_per_day']:
            return finish(_decision('SKIPPED_DAILY_CAP', matched, 'daily cap reached'))
        prompt = cfg['spawn']['prompt_template'].format(
            rules_doc=cfg['rules_doc'], entry_doc=cfg['entry_doc'])
        if mode == 'check':
            return finish(_decision('MATCHED', matched, 'check only', prompt=prompt))
        # Seen is marked on the attempt, not the outcome: a failed spawn must
        # not re-fire on the same issue every cooldown window; cron catches it.
        state['seen'].update({k: {'number': n} for k, n in matched})
        try:
            info = spawn_worker(cfg, state_dir, prompt, dry_run,
                                popen_fn=popen_fn, which_fn=which_fn)
        except OSError as exc:
            _advance_fire(state, now)
            return finish({'ok': False, 'event': 'ERROR',
                           'matched_numbers': [n for _, n in matched],
                           'reason': 'spawn failed: %s' % exc})
        _advance_fire(state, now)
        event = 'SPAWNED_DRYRUN' if dry_run else 'SPAWNED'
        return finish(_decision(event, matched, None, pid=info['pid'],
                                argv=info['argv'], prompt=prompt))
    except Exception as exc:  # noqa: BLE001 — the CLI contract is JSON, never a traceback
        decision = {'ok': False, 'event': 'ERROR', 'matched_numbers': [],
                    'reason': '%s: %s' % (type(exc).__name__, exc)}
        log_decision(state_dir, time.time(), decision)
        return decision


def main(argv=None, **deps):
    parser = argparse.ArgumentParser(prog='trigger.py')
    parser.add_argument('--config', required=True, help='machine-local triggers.json')
    sub = parser.add_subparsers(dest='mode', required=True)
    sub.add_parser('check', help='evaluate rules only, never spawn')
    run_parser = sub.add_parser('run', help='evaluate and spawn when allowed')
    run_parser.add_argument('--dry-run', action='store_true',
                            help='full pipeline without spawning the process')
    args = parser.parse_args(argv)
    decision = run(args.config, mode=args.mode,
                   dry_run=bool(getattr(args, 'dry_run', False)), **deps)
    print(json.dumps(decision, ensure_ascii=False, sort_keys=True))
    return 0 if decision.get('ok') else 1


if __name__ == '__main__':
    raise SystemExit(main())
