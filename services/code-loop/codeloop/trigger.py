def _round_claim_fields(round_claim):
    """Validate the prepared-round handoff values before they reach a prompt.
    They are machine-local runtime facts, but a malformed one is a programming
    error — loud, never a silently unscoped round."""
    if not isinstance(round_claim, dict):
        raise ValueError('ROUND_CLAIM_INVALID: must be a mapping')
    execution = round_claim.get('execution')
    token = round_claim.get('token')
    worktree = round_claim.get('worktree')
    if not isinstance(execution, str) or not execution:
        raise ValueError('ROUND_CLAIM_INVALID: execution')
    if isinstance(token, bool) or not isinstance(token, int) or token <= 0:
        raise ValueError('ROUND_CLAIM_INVALID: token must be a positive integer')
    if not isinstance(worktree, str) or not worktree or not Path(worktree).is_absolute():
        raise ValueError('ROUND_CLAIM_INVALID: worktree must be an absolute path')
    return execution, token, worktree


def _round_docs(loop, spec, row):
    """Resolve the loop's own rule/entry docs from the registration row. The
    registered docs belong to the reviewer loop (the registration is built by
    the review-trigger chain), so reviewer consumes them directly while the
    other loops resolve by convention: the rule doc beside the registered one
    (the register step derives reviewer.md into the skill's references/
    directory, and vendored project layouts mirror that sibling layout), the entry doc at
    the repo's ``.agents/loops/<loop>/prompt.md`` — soft: a project that never
    set that loop up has no entry file, and the round runs on the rules doc
    alone rather than naming a missing file."""
    if spec['rules_doc_mode'] == 'registered':
        rules_doc = row['rules_doc']
    else:
        rules_doc = loop_doc_path(row['rules_doc'], loop)
    if spec['entry_doc_mode'] == 'registered':
        entry_doc = row['entry_doc']
    else:
        candidate = Path(row['repo_cwd']) / '.agents' / 'loops' / loop / 'prompt.md'
        entry_doc = str(candidate) if candidate.is_file() else None
    return rules_doc, entry_doc


def _round_bootstrap(rules_doc, entry_doc):
    if entry_doc is None:
        return DEFAULT_PROMPT_TEMPLATE_NO_ENTRY.format(rules_doc=rules_doc)
    return DEFAULT_PROMPT_TEMPLATE.format(rules_doc=rules_doc, entry_doc=entry_doc)


def loop_doc_path(rules_doc, loop):
    """A non-reviewer loop's rule doc: beside the registered reviewer doc
    (the register step derives reviewer.md into the skill's references/
    directory, and vendored project layouts mirror that sibling layout), so a
    directive can name it without a second registration field. Missing is
    loud: the pre-claim check consumes this so an impossible round never
    costs a lease or a worktree."""
    doc = Path(rules_doc).parent / ('%s.md' % loop)
    if not doc.is_file():
        raise ValueError('%s_DOC_MISSING: %s — %s 手动轮需要规则文档同目录的 '
                         '%s.md（登记的 rules_doc=%s）'
                         % (loop.upper(), doc, loop, loop, rules_doc))
    return str(doc)


def build_round_prompt(loop, row, number=None, round_claim=None):
    """The one prompt constructor for dashboard-triggered rounds: a bootstrap
    in the loop's own context (its rule doc as 规则唯一源, its entry doc when
    one exists) plus the loop's directive, so no round ever reads another
    loop's rules under an override note. ``number`` is the dashboard card's PR
    number: None (an unscoped manual round — discover's shape) keeps the
    byte-identical cron template and refuses a claim; a positive int selects
    the targeted variant, which is the prepared one when ``round_claim`` (the
    dashboard's completed claim + worktree + bind handoff) is given, and the
    do-it-yourself variant for loops that have one. Anything else is a loud
    refusal, never a silently unscoped round. A new loop role plugs in by
    adding a LOOP_ROUND_SPECS entry."""
    spec = LOOP_ROUND_SPECS.get(loop)
    if spec is None:
        raise ValueError('UNKNOWN_ROUND_LOOP: %s（已知：%s）'
                         % (loop, ', '.join(sorted(LOOP_ROUND_SPECS))))
    if number is None:
        if round_claim is not None:
            raise ValueError('ROUND_CLAIM_WITHOUT_TARGET: round_claim needs a PR number')
        rules_doc, entry_doc = _round_docs(loop, spec, row)
        return _round_bootstrap(rules_doc, entry_doc)
    if isinstance(number, bool) or not isinstance(number, int) or number <= 0:
        raise ValueError('TARGET_INVALID: number must be a positive integer')
    if round_claim is None:
        suffix = spec['diy_suffix']
        if suffix is None:
            raise ValueError('ROUND_CLAIM_REQUIRED: %s 手动轮仅支持 prepared 交接'
                             '（看板先 claim + worktree + bind，再触发）' % loop)
        rules_doc, entry_doc = _round_docs(loop, spec, row)
        return _round_bootstrap(rules_doc, entry_doc) + suffix.format(number=number)
    if spec['prepared_suffix'] is None:
        raise ValueError('ROUND_CLAIM_WITHOUT_TARGET: %s 没有 prepared 定向轮' % loop)
    execution, token, worktree = _round_claim_fields(round_claim)
    rules_doc, entry_doc = _round_docs(loop, spec, row)
    kwargs = {'number': number, 'execution': execution, 'token': token,
              'worktree': worktree, 'rules_doc': rules_doc}
    for field, reason in spec['extra_claim_fields'].items():
        value = round_claim.get(field)
        if not isinstance(value, str) or not value:
            raise ValueError('ROUND_CLAIM_INVALID: %s (%s)' % (field, reason))
        kwargs[field] = value
    if loop == 'handler':
        task = round_claim.get('task') or 'PR_CONFLICT_RESOLUTION'
        reasons = round_claim.get('repair_reasons') or []
        kwargs['task'] = task
        kwargs['repair_reasons'] = ','.join(reasons) if reasons else task
        kwargs['repair_instruction'] = _repair_instruction(task, reasons)
        kwargs['uncertainty_instruction'] = _uncertainty_instruction(task, reasons)
    return (_round_bootstrap(rules_doc, entry_doc)
            + spec['prepared_suffix'].format(**kwargs))


def _repair_instruction(task, reasons):
    reasons = set(reasons or ())
    if task == 'PR_REVIEW_FIX' and 'validation_failed' in reasons:
        return ('先依据当前 head/base 的失败复现证据判定归属：PR head 红且基线绿才修 PR；'
                '分叉点红而当前基线绿则同步基线；当前基线也红或环境故障时不编辑 PR，'
                '记录证据并转入独立基线/门禁处理。')
    if task == 'PR_REVIEW_FIX' and 'merge_conflict' in reasons:
        return ('先按评审意见修复，再合并 origin/<基线分支> 并解决冲突；'
                '保留双方意图，完成两类修复后验证。')
    if task == 'PR_REVIEW_FIX':
        return '按 PR 的 changes-requested 评审意见修复，只处理评审指出的问题并验证。'
    if task == 'PR_CONFLICT_RESOLUTION':
        return ('按《PR 冲突解决（兜底）》规则合并 origin/<基线分支>，'
                '解决冲突并保留双方真实意图；'
                '无法判断时按规则报告 BLOCKED。')
    if task == 'PR_SYNC_BASE':
        return ('把 origin/<基线分支> 合入 PR 分支，消除已确认的基线差异；'
                '若出现冲突，按 Handler 冲突规则处理。')
    return '按 Handler 规则处理当前 repair work item 的 task 和 repair_reasons。'


def _uncertainty_instruction(task, reasons):
    if task == 'PR_REVIEW_FIX' and 'validation_failed' in set(reasons or ()):
        return '无法从 head/base 验证证据判定失败归属时按契约 report BLOCKED 并在 PR 留下命令、head/base SHA 和证据，不编辑 PR。'
    if task == 'PR_REVIEW_FIX' and 'merge_conflict' not in set(reasons or ()):
        return '无法判断评审意见时按契约 report BLOCKED 并留痕评论，不自行扩展修复范围。'
    return '判不了的冲突按契约 report BLOCKED 并留痕评论（禁止猜测），不硬造解决方案。'


